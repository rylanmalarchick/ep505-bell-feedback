"""Generate an integer rank certificate for the su(4) universality claim.

Finds 15 elements of the Lie algebra generated by i*{X1, Y1, 1X, 1Y, ZZ}
as explicit bracket words, a 15x15 integer minor S of their vectorization,
and the adjugate T with T*S = det(S)*I. Emits Lean source fragments for
EP505Su4.lean, where the kernel re-checks the certificate by decide.

Run: python gen_su4_certificate.py
"""

import sympy as sp
from sympy import I, Matrix, eye, zeros

sx = Matrix([[0, 1], [1, 0]])
sy = Matrix([[0, -I], [I, 0]])
sz = Matrix([[1, 0], [0, -1]])
id2 = eye(2)


def kron(a, b):
    out = zeros(4, 4)
    for i in range(2):
        for j in range(2):
            out[2 * i:2 * i + 2, 2 * j:2 * j + 2] = a[i, j] * b
    return out


gens = [("g0", I * kron(sx, id2)), ("g1", I * kron(sy, id2)),
        ("g2", I * kron(id2, sx)), ("g3", I * kron(id2, sy)),
        ("g4", I * kron(sz, sz))]


def vec(M):
    return [f(M[i, j]) for i in range(4) for j in range(4)
            for f in (sp.re, sp.im)]


elems = list(gens)                      # (name, matrix); name doubles as word
rows = Matrix([vec(M) for _, M in elems])
words = []                              # (new_index, left_index, right_index)
for _ in range(4):                      # depth bound; rank 15 hit well before
    if rows.rank() == 15:
        break
    for a in range(len(elems)):
        for b in range(a + 1, len(elems)):
            br = elems[a][1] * elems[b][1] - elems[b][1] * elems[a][1]
            cand = rows.col_join(Matrix([vec(br)]))
            if cand.rank() > rows.rank():
                k = len(elems)
                elems.append((f"e{k}", br))
                words.append((k, a, b))
                rows = cand
            if rows.rank() == 15:
                break
        if rows.rank() == 15:
            break
assert rows.rank() == 15, f"closure stalled at rank {rows.rank()}"
assert len(elems) == 15

pivots = rows.rref()[1]                 # pivot columns of the 15x32 matrix
S = rows[:, list(pivots)]
d = S.det()
T = S.adjugate()
assert d != 0 and T * S == d * eye(15) and S * T == d * eye(15)
assert all(M.trace() == 0 for _, M in elems)
assert all((M.H + M) == zeros(4, 4) for _, M in elems)

print(f"-- generated by gen_su4_certificate.py; det = {d}")
print("-- bracket words:")
for k, a, b in words:
    print(f"def e{k} : Mat := bracket {elems[a][0]} {elems[b][0]}")
print("\n-- es table arms (Fin 15 -> Mat):")
print("  " + " ".join(f"| {k} => {name}" for k, (name, _) in enumerate(elems)))
print("\n-- coordinate selectors (pivot columns):")
for n, c in enumerate(pivots):
    i, j, part = c // 8, (c % 8) // 2, ("re" if c % 2 == 0 else "im")
    print(f"  | {n} => (M {i} {j}).{part}")
print(f"\ndef dcert : Int := {d}")
print("\n-- adjugate rows (List Int):")
for r in range(15):
    print(f"  | {r} => [" + ", ".join(str(T[r, c]) for c in range(15)) + "]")
